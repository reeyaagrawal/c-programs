int main(){
    int a=5*2-2*3;//(5*2)-(2*3)=10-6=4
    int b=5*2/2*3;//((5*2)/2)*3=(10/2)*3=5*3=15
    int c=5*(2/2)*3;//5*1*3=15
    int d=5+2/2*3;//5+1*3=5+3=8
    printf("a= %d",a);
    printf("\nb= %d",b);
    printf("\nc= %d",c);
    printf("\nd= %d",d);
    return 0;
}